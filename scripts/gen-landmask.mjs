#!/usr/bin/env node
// Rasterises each home country's surroundings (Natural Earth 1:50m admin-0 land, public domain)
// onto the game's tile-corner grid and writes src/world/content/landmasks.ts.
//
//   node scripts/gen-landmask.mjs [path/to/ne_50m_admin_0_countries.geojson]
//
// Without a path it downloads the data. The projection must match src/world/content/geo.ts.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const DATA_URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson';
const params = JSON.parse(readFileSync(new URL('../src/world/content/geoParams.json', import.meta.url), 'utf8'));

async function load() {
  const path = process.argv[2];
  if (path && existsSync(path)) return JSON.parse(readFileSync(path, 'utf8'));
  const res = await fetch(DATA_URL);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  return res.json();
}

/** Grid size: a fixed 72x56 unless the country asks for a ground scale (km per tile). */
function sizeOf(p) {
  if (!p.km) return [72, 56];
  const k = Math.cos((((p.lat[0] + p.lat[1]) / 2) * Math.PI) / 180);
  return [Math.round(((p.lon[1] - p.lon[0]) * k * 111) / p.km), Math.round(((p.lat[1] - p.lat[0]) * 111) / p.km)];
}

function projection(p, W, H) {
  const [latMin, latMax] = p.lat;
  const [lonMin, lonMax] = p.lon;
  const latC = (latMin + latMax) / 2;
  const lonC = (lonMin + lonMax) / 2;
  const k = Math.cos((latC * Math.PI) / 180);
  const scale = Math.min(W / ((lonMax - lonMin) * k), H / (latMax - latMin));
  return {
    fromTile: (x, y) => ({ lat: latC - (y - H / 2) / scale, lon: lonC + (x - W / 2) / (scale * k) }),
  };
}

function inRing(ring, lon, lat) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const geo = await load();
const polys = [];
for (const f of geo.features) {
  const g = f.geometry;
  const list = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const rings of list) {
    let minX = 1e9, maxX = -1e9, minY = 1e9, maxY = -1e9;
    for (const [x, y] of rings[0]) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
    polys.push({ rings, minX, maxX, minY, maxY, admin: f.properties.ADMIN });
  }
}

const homeOut = [];
let out = `/* Generated by scripts/gen-landmask.mjs from Natural Earth (public domain). Do not edit. */\n/** Land (1) / sea (0) at each tile corner, row by row, packed 8 to a byte, base64. */\nexport const LANDMASKS: Record<string, string> = {\n`;
const sizes = {};
for (const [code, p] of Object.entries(params)) {
  const [W, H] = sizeOf(p);
  sizes[code] = [W, H];
  const proj = projection(p, W, H);
  const bits = [];
  const home = [];
  for (let y = 0; y <= H; y++) {
    for (let x = 0; x <= W; x++) {
      const { lat, lon } = proj.fromTile(x, y);
      let land = 0;
      let mine = 0;
      for (const poly of polys) {
        if (lon < poly.minX || lon > poly.maxX || lat < poly.minY || lat > poly.maxY) continue;
        // Even-odd across the outer ring and any holes.
        let inside = false;
        for (const ring of poly.rings) if (inRing(ring, lon, lat)) inside = !inside;
        if (!inside) continue;
        land = 1;
        if (poly.admin === p.admin) mine = 1;
        if (mine) break;
      }
      bits.push(land);
      home.push(mine);
    }
  }
  const pack = list => {
    const bytes = new Uint8Array(Math.ceil(list.length / 8));
    list.forEach((b, i) => { if (b) bytes[i >> 3] |= 1 << (i & 7); });
    return Buffer.from(bytes).toString('base64');
  };
  homeOut.push(`  ${code}: '${pack(home)}',\n`);
  out += `  ${code}: '${pack(bits)}',\n`;
  const rows = [];
  for (let y = 0; y <= H; y += 2) rows.push(bits.slice(y * (W + 1), (y + 1) * (W + 1)).map((b, x) => (home[y * (W + 1) + x] ? 'H' : b ? '#' : '.')).join(''));
  console.log(`--- ${code}\n${rows.join('\n')}`);
}
out += '};\n\n/** Grid size (tiles) of each country. */\nexport const SIZES: Record<string, [number, number]> = ' + JSON.stringify(sizes) + ';\n\n/** The same grid, but only the country itself (neighbours are sea-level-neutral foreign land). */\nexport const HOMEMASKS: Record<string, string> = {\n' + homeOut.join('') + '};\n';
writeFileSync(new URL('../src/world/content/landmasks.ts', import.meta.url), out);
console.log('written');
