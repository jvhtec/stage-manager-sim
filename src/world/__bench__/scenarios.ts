const SHOCK_LABELS: Record<string, string> = {
  'lose-client': 'Biggest client walks',
  recall: 'Fleet recall',
  downturn: 'Economic downturn',
  'late-payers': 'Late-paying promoters',
};
export const shockName = (r: Pick<BotReport, 'shockLog'>) => (r.shockLog.length ? (r.shockLog.length > 1 ? 'All four at once' : SHOCK_LABELS[r.shockLog[0].kind] ?? r.shockLog[0].kind) : 'No shock (control)');

/** The month the first shock hit, the value then, and how long until the company was worth that again. */
export function recovery(r: Pick<BotReport, 'series' | 'shockLog'>, shockDay?: number): { at?: BotMonth; months?: number; lowCash: number; repDip: number } {
  const day = r.shockLog[0]?.day;
  // The control run: the lowest cash over the same stretch the shocked runs are measured on.
  if (day === undefined) return { lowCash: Math.min(...r.series.filter(m => m.day > (shockDay ?? -1)).map(m => m.cash)), repDip: 0 };
  const at = [...r.series].reverse().find(m => m.day <= day) ?? r.series[0];
  const after = r.series.filter(m => m.day > day);
  const back = after.find(m => m.value >= at.value);
  return {
    at,
    months: back ? Math.round((back.day - at.day) / 30) : undefined,
    lowCash: Math.min(...after.map(m => m.cash), at.cash),
    repDip: Math.min(0, ...after.map(m => m.reputation - at.reputation)),
  };
}

/**
 * The year after a shock, against the same seed left alone. Up to the shock the two runs are the
 * same game move for move, so the first twelve months show the damage itself; further out, the
 * runs drift apart for every reason a business does, and the end-of-run gap is mostly that drift.
 */
export function shockWindow(r: Pick<BotReport, 'series'>, control: Pick<BotReport, 'series'>, shockDay: number, months = 12) {
  const i0 = Math.max(0, r.series.findIndex(m => m.day > shockDay) - 1);
  const at = (x: Pick<BotReport, 'series'>, i: number) => x.series[Math.min(i, x.series.length - 1)];
  const span = (x: Pick<BotReport, 'series'>) => x.series.slice(i0 + 1, i0 + 1 + months);
  const delta = (x: Pick<BotReport, 'series'>, f: (m: BotMonth) => number) => f(at(x, i0 + months)) - f(at(x, i0));
  const ratio = (a: number, b: number) => (b ? (a - b) / Math.abs(b) : 0);
  return {
    income: ratio(delta(r, m => m.income), delta(control, m => m.income)),
    shows: ratio(delta(r, m => m.shows), delta(control, m => m.shows)),
    lowCash: Math.min(...span(r).map(m => m.cash)),
    controlLowCash: Math.min(...span(control).map(m => m.cash)),
    reputation: at(r, i0 + months).reputation - at(control, i0 + months).reputation,
    value: ratio(at(r, i0 + months).value, at(control, i0 + months).value),
  };
}

export function renderAdverse(reports: BotReport[], strategies: Strategy[], meta: { years: number; runs: string; shockDay: number }): string {
  const lines: string[] = ['# Adverse scenarios', ''];
  lines.push(`Generated by \`npm run balance:adverse\` — ${meta.runs}, ${meta.years} years each. ${Math.round((meta.shockDay / 365) * 10) / 10} years in, once the company is established, one thing goes badly wrong — or all four within two months — and the run is compared with the same seed left alone. Up to the shock the two are the same game move for move, so the twelve months after it show the damage itself; the end-of-run column also carries every other way two eight-year runs drift apart.`);
  lines.push('');
  lines.push('- **Biggest client walks**: the act that paid the most this year and last (counting what it has booked) signs with a rival. Its booked shows are cancelled on their contract terms (deposits and cancellation clauses pay out, if you have them) and it won’t book you for two years.');
  lines.push('- **Fleet recall**: the maker calls in the model most of the fleet runs on. Those trucks finish the trip they’re on and sit at the dealer for 12 days; shows booked onto them need another truck.');
  lines.push('- **Economic downturn**: 18 months of 30% less work at fees 15% lower; defaults double and clients cancel more while demand is down.');
  lines.push('- **Late-paying promoters**: for a year, invoices go late three times as often, and up to twice as late.');
  lines.push('');
  const fmt = (d: number) => signed(d * 100, n => `${Math.round(n)}%`);
  byCohort(reports).forEach(cohort => {
    const k = moneyOf(cohort[0]);
    lines.push(`## ${cohortTitle(cohort[0])}`);
    lines.push('');
    lines.push('| Strategy | Shock | Survived | Show income, next 12 months | Shows played, next 12 months | Lowest cash, next 12 months (no shock) | Reputation 12 months on | Value 12 months on | Value at the end | Overdrawn months | What it hit |');
    lines.push('|---|---|---|---|---|---|---|---|---|---|---|');
    strategies.forEach(st => {
      const rs = cohort.filter(r => r.strategy === st.id);
      const names = [...new Set(rs.map(shockName))].filter(n => n !== shockName({ shockLog: [] }));
      names.forEach(name => {
        const runs = rs.filter(r => shockName(r) === name);
        const pairs = runs.map(r => [r, rs.find(c => c.seed === r.seed && !c.shockLog.length)] as const).filter((p): p is readonly [BotReport, BotReport] => !!p[1]);
        const w = pairs.map(([r, c]) => shockWindow(r, c, meta.shockDay));
        const end = pairs.map(([r, c]) => (c.value ? (r.value - c.value) / Math.abs(c.value) : 0));
        const od = pairs.map(([r, c]) => r.monthsOverdrawn - c.monthsOverdrawn);
        const what = [...new Set(runs.flatMap(r => r.shockLog.map(x => x.what.replace(/ \(.*\)$/, ''))))];
        lines.push(
          `| ${st.label} | ${name} | ${runs.filter(r => r.survived).length}/${runs.length} | ${w.map(x => fmt(x.income)).join(' / ')} | ${w.map(x => fmt(x.shows)).join(' / ')} | ${w.map(x => `${k(x.lowCash)} (${k(x.controlLowCash)})`).join(' / ')} | ${w.map(x => signed(x.reputation, n => n.toFixed(1))).join(' / ')} | ${w.map(x => fmt(x.value)).join(' / ')} | ${end.map(fmt).join(' / ')} | ${od.map(d => signed(d, n => `${n}`)).join(' / ')} | ${what.join('; ')} |`,
        );
      });
    });
    lines.push('');
  });
  lines.push('Each cell lists the seeds in order, as change against the same seed with no shock. Lowest cash shows the shocked run with the untouched one in brackets.');
  lines.push('');
  return lines.join('\n');
}

