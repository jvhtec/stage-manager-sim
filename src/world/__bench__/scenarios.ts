/**
 * Write-ups for the scenario benches: management systems switched off one at a time
 * (ablation.bench.ts), shocks thrown at a running company (adverse.bench.ts), and reputation
 * over thirty years (decades.bench.ts). Every table is per cohort — one country from one start
 * year — and in that cohort's own money; anything compared across countries is a ratio.
 */
import type { BotMonth, BotReport, Feature, Strategy } from './bot';
import { byCohort, cohortTitle, marginOf, median, moneyOf } from './report';

const pct = (n: number) => `${Math.round(n * 100)}%`;
const signed = (n: number, f: (x: number) => string) => (n >= 0 ? `+${f(n)}` : `−${f(-n)}`);
const pts = (n: number) => `${n >= 0 ? '+' : '−'}${Math.abs(Math.round(n * 1000) / 10)} pts`;
const failRate = (r: BotReport) => r.failed / Math.max(1, r.shows + r.failed);
const uncovered = (r: BotReport) => r.incidents.causes['no-terms'] ?? 0;

// ---------------------------------------------------------------------------
// Ablation
// ---------------------------------------------------------------------------

export function renderAblation(reports: BotReport[], variants: Strategy[], systems: { id: Feature; label: string }[], meta: { years: number; runs: string }): string {
  const lines: string[] = ['# Management systems, one at a time', ''];
  lines.push(`Generated by \`npm run balance:ablation\` — ${meta.runs}, ${meta.years} years each. The managed company plays the same seed with every system on, then with each one switched off in turn, then with none. Same seed means the same world and the same first offers; after that the runs drift apart, so a difference counts only when it points the same way on every seed.`);
  lines.push('');
  const full = variants[0].id;
  const summary: { label: string; deltas: number[] }[] = variants.slice(1).map(v => ({ label: v.label, deltas: [] }));
  byCohort(reports).forEach(cohort => {
    const k = moneyOf(cohort[0]);
    const seeds = [...new Set(cohort.map(r => r.seed))];
    const run = (id: string, seed: number) => cohort.find(r => r.strategy === id && r.seed === seed);
    lines.push(`## ${cohortTitle(cohort[0])}`);
    lines.push('');
    lines.push(`| Managed company… | Value (seeds ${seeds.join(' / ')}) | Δ value vs all on | Seeds better / worse | Δ margin | Failed shows | Overdrawn months | Cancellations with nothing to claim | Crew lost |`);
    lines.push('|---|---|---|---|---|---|---|---|---|');
    variants.forEach((v, i) => {
      const rs = seeds.map(sd => run(v.id, sd)).filter((r): r is BotReport => !!r);
      if (!rs.length) return;
      const pairs = seeds.map(sd => [run(v.id, sd), run(full, sd)] as const).filter((p): p is readonly [BotReport, BotReport] => !!p[0] && !!p[1]);
      const dv = pairs.map(([a, b]) => a.value - b.value);
      const dm = pairs.map(([a, b]) => marginOf(a) - marginOf(b));
      if (i > 0) summary[i - 1].deltas.push(...pairs.map(([a, b]) => (a.value - b.value) / Math.max(1, Math.abs(b.value))));
      const better = dv.filter(d => d > 0).length;
      const worse = dv.filter(d => d < 0).length;
      lines.push(
        `| ${i === 0 ? '**with everything on**' : v.label} | ${rs.map(r => (r.survived ? k(r.value) : `bust (${r.yearsRun}y)`)).join(' / ')} | ${i === 0 ? '—' : signed(median(dv), k)} | ${i === 0 ? '—' : `${better} / ${worse}`} | ${i === 0 ? pct(median(rs.map(marginOf))) : pts(median(dm))} | ${pct(median(rs.map(failRate)))} | ${median(rs.map(r => r.monthsOverdrawn))} | ${median(rs.map(uncovered))} | ${median(rs.map(r => r.crewLost))} |`,
      );
    });
    lines.push('');
  });
  lines.push('## Across countries');
  lines.push('');
  lines.push('What switching each system off did to company value, as a share of the all-on run on the same seed — a ratio, so the countries can sit side by side.');
  lines.push('');
  lines.push('| Managed company… | Median change in value | Runs worse / better | Verdict |');
  lines.push('|---|---|---|---|');
  summary.forEach(x => {
    const worse = x.deltas.filter(d => d < 0).length;
    const better = x.deltas.filter(d => d > 0).length;
    const m = median(x.deltas);
    const verdict = !x.deltas.length
      ? '—'
      : !worse && !better
        ? 'never came into play on these runs'
        : Math.abs(m) < 0.02
          ? 'no clear effect: inside the seed-to-seed drift'
          : worse === x.deltas.length
            ? 'pays its way on every run'
            : better === x.deltas.length
              ? 'the company does better without it on every run'
              : `mixed (${worse} worse, ${better} better)`;
    lines.push(`| ${x.label} | ${signed(m * 100, n => `${Math.round(n)}%`)} | ${worse} / ${better} | ${verdict} |`);
  });
  lines.push('');
  lines.push('A system that shows no clear effect isn’t necessarily useless: it may only matter in the bad years these seeds didn’t have (see the adverse scenarios), or its value may sit inside what one lost contract does to an eight-year run. The systems are listed in bot.ts (`managed` strategy).');
  lines.push('');
  void systems;
  return lines.join('\n');
}

