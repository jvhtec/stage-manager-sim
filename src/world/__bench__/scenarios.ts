/** Year-end reputation (the last month sampled in each calendar year). */
export function yearly(series: BotMonth[]): { year: number; reputation: number; value: number }[] {
  const by = new Map<number, BotMonth>();
  series.forEach(m => by.set(m.year, m));
  return [...by.values()].map(m => ({ year: m.year, reputation: m.reputation, value: m.value }));
}

/** The worst fall from a peak, and how many years it took to get back to within 5 points of that peak. */
export function worstDecline(years: { year: number; reputation: number }[]): { from: number; to: number; drop: number; recovered?: number } | undefined {
  let best: { from: number; to: number; drop: number; recovered?: number } | undefined;
  for (let i = 0; i < years.length; i++)
    for (let j = i + 1; j < years.length; j++) {
      const drop = years[i].reputation - years[j].reputation;
      if (drop > (best?.drop ?? 0)) {
        const back = years.slice(j + 1).find(y => y.reputation >= years[i].reputation - 5);
        best = { from: years[i].year, to: years[j].year, drop, recovered: back ? back.year - years[j].year : undefined };
      }
    }
  return best;
}

export function renderDecades(reports: BotReport[], meta: { years: number; runs: string; shockYear: number }): string {
  const lines: string[] = ['# Reputation over decades', ''];
  lines.push(`Generated by \`npm run balance:decades\` — ${meta.runs}, ${meta.years} years each, with and without everything going wrong at once in year ${meta.shockYear} (biggest client walks, fleet recall, downturn, late payers). Reputation is 0–100; each venue tier caps what its shows can earn you, failed shows cost more at bigger venues, and good ones earn less the higher you already are.`);
  lines.push('');
  byCohort(reports).forEach(cohort => {
    const k = moneyOf(cohort[0]);
    lines.push(`## ${cohortTitle(cohort[0])}`);
    lines.push('');
    const all = cohort.map(r => ({ r, ys: yearly(r.series) }));
    const years = [...new Set(all.flatMap(x => x.ys.map(y => y.year)))].filter((y, i) => i % 5 === 0 || i === 0);
    lines.push(`| Run | ${years.join(' | ')} | End | Worst decline | Years to recover |`);
    lines.push(`|---|${years.map(() => '---').join('|')}|---|---|---|`);
    all.forEach(({ r, ys }) => {
      const at = (y: number) => ys.find(x => x.year === y)?.reputation;
      const d = worstDecline(ys);
      lines.push(
        `| ${r.strategy}, seed ${r.seed}${r.shockLog.length ? ', shocked' : ''}${r.survived ? '' : ` (bust ${r.yearsRun}y)`} | ${years.map(y => (at(y) === undefined ? '' : Math.round(at(y)!))).join(' | ')} | ${r.reputation} (${k(r.value)}) | ${d && d.drop >= 3 ? `−${Math.round(d.drop)} (${d.from}→${d.to})` : 'none'} | ${d && d.drop >= 3 ? (d.recovered === undefined ? 'not recovered' : `${d.recovered}`) : '—'} |`,
      );
    });
    lines.push('');
    const shocked = all.filter(x => x.r.shockLog.length);
    shocked.forEach(({ r }) => {
      const rec = recovery(r);
      const ctrl = cohort.find(c => c.seed === r.seed && c.strategy === r.strategy && !c.shockLog.length);
      lines.push(`- ${r.strategy}, seed ${r.seed}: hit in ${rec.at?.year} at reputation ${rec.at?.reputation}; reputation fell ${Math.abs(rec.repDip).toFixed(1)} points; value back to its pre-shock level after ${rec.months === undefined ? 'never, within the run' : `${rec.months} months`}; ended at reputation ${r.reputation} against ${ctrl?.reputation ?? '?'} without the shock.`);
    });
    if (shocked.length) lines.push('');
  });
  return lines.join('\n');
}
