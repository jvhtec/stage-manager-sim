import { afterAll, it } from 'vitest';
import { mkdirSync, writeFileSync } from 'node:fs';
import { runBot, STRATEGIES, type BotReport } from './bot';
import { reportsJson } from './report';
import { HISTORY } from '../historyFlags';
import type { CountryCode } from '../content/countries';

/**
 * The historical market, one layer at a time (docs/research/historical-market-architecture.md §24):
 * the same company, countries and seeds with the market built up step by step —
 *   chronology only → + specialised firms (subcontracting on the hire market) → + partner firms
 *   → + local competition (everything on, as the game runs).
 *
 *   npm run balance:history
 *   HISTORY_RUNS='[["ES",1990]]' HISTORY_SEEDS='[3]' HISTORY_YEARS=6 npm run balance:history
 */
const RUNS: [CountryCode, number][] = JSON.parse(process.env.HISTORY_RUNS ?? '[["ES",1990],["GB",1995]]');
const SEEDS: number[] = JSON.parse(process.env.HISTORY_SEEDS ?? '[3,4,5,6]');
const YEARS = Number(process.env.HISTORY_YEARS ?? 8);
const OUT = process.env.HISTORY_OUT ?? 'docs/balance-history';

const LAYERS = [
  { id: 'chronology', label: 'Chronology only (every firm runs every department)', flags: { specialization: false, partners: false, localCrowding: false } },
  { id: 'specialised', label: '+ specialised firms, missing departments from the hire market', flags: { specialization: true, partners: false, localCrowding: false } },
  { id: 'partners', label: '+ partner firms', flags: { specialization: true, partners: true, localCrowding: false } },
  { id: 'local', label: '+ local competition (the game as it runs)', flags: { specialization: true, partners: true, localCrowding: true } },
];

const ONLY: string[] | undefined = process.env.HISTORY_LAYERS ? JSON.parse(process.env.HISTORY_LAYERS) : undefined;
const results: { layer: string; r: BotReport }[] = [];
LAYERS.filter(l => !ONLY || ONLY.includes(l.id)).forEach(layer => {
  it(`layer: ${layer.id}`, () => {
    Object.assign(HISTORY, layer.flags);
    for (const [country, startYear] of RUNS)
      for (const seed of SEEDS) {
        const r = runBot({ country, startYear, years: YEARS, seed, strategy: STRATEGIES.baseline });
        results.push({ layer: layer.id, r });
        console.log(layer.id, country, startYear, seed, r.survived ? 'alive' : 'bust', Math.round(r.value / 1000), 'k', 'rival shows', r.rivals.shows);
      }
    Object.assign(HISTORY, LAYERS[LAYERS.length - 1].flags);
  });
});

const median = (xs: number[]) => {
  const v = [...xs].sort((a, b) => a - b);
  return v.length ? (v.length % 2 ? v[(v.length - 1) / 2] : (v[v.length / 2 - 1] + v[v.length / 2]) / 2) : 0;
};
const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)}%` : '—');
const k = (n: number) => (Math.abs(n) >= 1e6 ? `${(n / 1e6).toFixed(1)}M` : `${Math.round(n / 1000)}k`);

afterAll(() => {
  const lines: string[] = [];
  lines.push('# Historical market: what each layer changes', '');
  lines.push(`Generated by \`npm run balance:history\` — the baseline company, ${RUNS.map(([c, y]) => `${c} ${y}`).join(' and ')}, seeds ${SEEDS.join(', ')}, ${YEARS} years each. Deterministic.`, '');
  lines.push('Each layer adds one part of the historical market model (docs/research/historical-market-architecture.md). Values are in game units (not converted to local money), so compare across rows, not across countries.', '');
  for (const [country, startYear] of RUNS) {
    lines.push(`## ${country} from ${startYear}`, '');
    lines.push('| Layer | Survived | Median value | Your shows | Rival shows | Rival failed | Rival shows subcontracting | Partner jobs | Rivals alive / gone at the end |');
    lines.push('|---|---|---|---|---|---|---|---|---|');
    LAYERS.forEach(layer => {
      const rs = results.filter(x => x.layer === layer.id && x.r.country === country && x.r.startYear === startYear).map(x => x.r);
      if (!rs.length) return;
      const rivalShows = rs.reduce((n, r) => n + r.rivals.shows, 0);
      lines.push(
        `| ${layer.label} | ${rs.filter(r => r.survived).length}/${rs.length} | ${k(median(rs.map(r => r.value)))} | ${median(rs.map(r => r.shows))} | ${median(rs.map(r => r.rivals.shows))} | ${pct(rs.reduce((n, r) => n + r.rivals.failed, 0), rivalShows)} | ${pct(rs.reduce((n, r) => n + r.rivals.subcontracted, 0), rivalShows)} | ${median(rs.map(r => r.rivals.partnered))} | ${median(rs.map(r => r.rivals.alive))} / ${median(rs.map(r => r.rivals.gone))} |`,
      );
    });
    lines.push('');
    // The market itself at the end of each full-model run: who was drawn, who's left and what they run.
    lines.push('**The market at the end** (all layers on):', '');
    results
      .filter(x => x.layer === 'local' && x.r.country === country && x.r.startYear === startYear)
      .forEach(({ r }) => {
        lines.push(`- Seed ${r.seed}: ${r.market.alive.map(a => `${a.name} (${a.depts.join(', ') || 'no kit'})`).join('; ')}.`);
        const events = r.market.events.filter(e => Number(e.split(':')[2]) > startYear);
        if (events.length) lines.push(`  Company events: ${events.join(', ')}. Gone: ${r.market.gone.join(', ') || 'none'}.`);
      });
    lines.push('');
  }
  mkdirSync(OUT.split('/').slice(0, -1).join('/') || '.', { recursive: true });
  writeFileSync(`${OUT}.md`, lines.join('\n'));
  writeFileSync(`${OUT}.json`, reportsJson(results.map(x => ({ ...x.r, strategy: `${x.r.strategy}:${x.layer}` }))));
  console.log(`Wrote ${OUT}.md and ${OUT}.json`);
});
